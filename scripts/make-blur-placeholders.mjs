// Builds data/blur-placeholders.ts: a tiny blurred preview of every photo, shown while the real image loads.
// Run after adding or replacing photos: node scripts/make-blur-placeholders.mjs
import { readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import sharp from 'sharp';

const root = process.cwd();
const folders = ['public/images/photos', 'public/images/real-estate', 'public/images/hero'];

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (/\.(webp|jpe?g)$/i.test(entry.name)) yield path;
  }
}

const entries = [];
for (const folder of folders) {
  for await (const file of walk(join(root, folder))) {
    const buffer = await sharp(file).resize(12, 12, { fit: 'inside' }).webp({ quality: 40 }).toBuffer();
    const src = '/' + relative(join(root, 'public'), file).split(sep).join('/');
    entries.push([src, `data:image/webp;base64,${buffer.toString('base64')}`]);
  }
}
entries.sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([src, data]) => `  '${src}': '${data}',`).join('\n');
await writeFile(join(root, 'data/blur-placeholders.ts'), `// Generated by scripts/make-blur-placeholders.mjs. Do not edit by hand.\n// 12px previews of each photo, blurred by next/image while the full photo loads.\n\nexport const blurPlaceholders: Record<string, string> = {\n${body}\n};\n`);
console.log(`${entries.length} placeholders, ${body.length} bytes`);
